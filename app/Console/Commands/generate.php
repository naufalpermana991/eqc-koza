<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;


class generate extends Command
{
    protected $signature = "generate:crud {tablename} {dir?}";
    protected $description = "Generate CRUD of master data";

    public function handle()
    {
        $tablename = strtolower($this->argument("tablename"));
        $dir = $this->argument("dir");
        if($dir) {
            $dir = str_replace(".", "/", $dir);
            $dir = explode("/", $dir);
        } else {
            $dir = [];
        }

        /**
         * Check existing tablename
         * */
        $data = DB::select("
            SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
        ");

        $table_exists = false;
        for($i = 0; $i < count($data); $i++) {
            if(strtolower($data[$i]->table_name) === $tablename) {
                $table_exists = true;
                break;
            }
        }
        if(!$table_exists) {
            $this->error("Table you input is not exists");
            die();
        }

        /**
         * Check existing file before create
         * 
         * -- Then --
         * 
         * Creating folder and files in
         * app/Http/Controllers
         * app/Models
         * resources/views/contents
         * */

        $controller_path = "Http/Controllers";
        $model_path = "Models";
        $view_path = "resources/views/contents";

        for($i = 0; $i < count($dir); $i++) {
            $controller_path .= "/{$dir[$i]}";
            $model_path .= "/{$dir[$i]}";
            $view_path .= "/{$dir[$i]}";
        }
        $camel_case_name = $this->upper_first_letter($tablename);

        $controller_path .= "/{$camel_case_name}";
        $model_path .= "/{$camel_case_name}";

        /**
         * Check existing files
         * */

        if(file_exists(__DIR__ . "/../../{$controller_path}.php")) {
            $this->error("Controller is already exists: {$controller_path}.php");
            die();
        }

        if(file_exists(__DIR__ . "/../../{$model_path}")) {
            $this->error("Model is already exists: {$model_path}.php");
            die();
        }

        /**
         * Create dynamic folder - with Anonymous function
         * */

        function _createDirectory($routepath, $directories, $is_view = false): void
        {
            $_filepath = __DIR__ . ($is_view ? "/../../../{$routepath}" : "/../../{$routepath}");
            for($i = 0; $i < count($directories); $i++) {
                $_filepath .= "/{$directories[$i]}";
                if(!is_dir($_filepath)) {
                    /**
                     * Create directory
                     * */
                    mkdir($_filepath, 0777, true);
                }
            }
        }
        _createDirectory("Http/Controllers", $dir);
        _createDirectory("Models", $dir);
        _createDirectory("resources/views/contents", [...$dir, $tablename], true);

        /**
         * Get detail fields by table
         * */
        $columns = DB::select("
            SELECT column_name,udt_name FROM information_schema.columns WHERE table_schema = 'public' AND table_name = '$tablename'
        ");

        /**
         * Create routing
         * */
        $this->generate_routing($tablename, $camel_case_name, $controller_path);

        /**
         * Generate controller
         * */
        $this->generate_controller($tablename, $camel_case_name, $columns, $dir, $controller_path, $model_path);

        /**
         * Generate model
         * */
        $this->generate_model($tablename, $camel_case_name, $columns, $dir, $model_path);

        /**
         * Generate view
         * */
        $this->generate_view($tablename, $camel_case_name, $columns, $dir, $view_path);
    }


    /**
     * Function below for replicate base files to the new one
     * */

    protected function upper_first_letter($string): string
    {
        $response = "";
        for($i = 0; $i < strlen($string); $i++) {
            if($i === 0) {
                $response .= strtoupper($string[$i]);
            } else {
                $response .= $string[$i];
            }
        }
        return $response;
    }

    protected function generate_routing(
        $tablename, 
        $controller_name, 
        $controller_path
    ): void
    {
        $routes = fopen(__DIR__ . "./../../../routes/web.php", "r+");
        $new_route = "\n\n/**\n * Route for table '{$tablename}' - Generated by system\n **/\n";
        $new_route .= "use App\\".str_replace("/", "\\", $controller_path).";\n";
        $new_route .= "
Route::prefix('{$tablename}')->group(function() {
    Route::get('/', [{$controller_name}::class, 'index'])->name('{$tablename}.list');
    Route::get('/show/{id}', [{$controller_name}::class, 'show'])->name('{$tablename}.show');
    Route::get('/create', [{$controller_name}::class, 'create'])->name('{$tablename}.create_form');
    Route::post('/create', [{$controller_name}::class, 'create'])->name('{$tablename}.create_action');
    Route::post('/update/{id}', [{$controller_name}::class, 'update'])->name('{$tablename}.update_action');
    Route::get('/delete/{id}', [{$controller_name}::class, 'delete'])->name('{$tablename}.delete');
});
        ";
        while($line = fgets($routes, 4096)) {
            /** let this one empty **/
        }

        fputs($routes, $new_route);
        fclose($routes);
    }

    protected function generate_controller(
        $tablename, 
        $camel_case_name, 
        $columns, 
        $dir, 
        $controller_path, 
        $model_path
    ): void
    {
        $controller = fopen(__DIR__ . "./../../../app/{$controller_path}.php", "w");

        /**
         * Write controller base here
         * 
         * Dynamic variables detected
         * @var __NAMESPACE__ (String) for file_route
         * @var __MODEL_PATH__ (String) for model file
         * @var __CONTROLLER_NAME__ (String) with camel case
         * @var __MODEL_NAME__ (String) like a __CONTROLLER_NAME__
         * @var __FIELD_TO_GET__ (String) field that show in table --> field1, field2, etc
         * @var __MAIN_ROUTES__ (String) registered route in routes/web.php --> settings.users.list
         * @var __VIEW_PATH__ (String) path to open views
         * @var __DATA_TO_INSERT__ (Array to String) array data(s) will inserted to database
         * */

        $base_controller = fopen(__DIR__ . "./../../../public/__BASE__/__CONTROLLER__.txt", "r+");
        $base_codes = "";
        while($line = fgets($base_controller, 4096)) {
            $base_codes .= $line;
        }

        /**
         * Replacing content
         * */
        $model_name = "{$camel_case_name}Model";

        $base_codes = str_replace("{{__CONTROLLER_NAME__}}", $camel_case_name, $base_codes);
        $base_codes = str_replace("{{__MODEL_NAME__}}", $model_name, $base_codes);
        $base_codes = str_replace("{{__MAIN_ROUTES__}}", $tablename, $base_codes);

        /**
         * Controller
         * */
        $controller_main_path = "App";
        $controller_array = explode("/", $controller_path);
        for($i = 0; $i < count($controller_array); $i++) {
            if($i < (count($controller_array) - 1)) {
                $controller_main_path .= "\\{$controller_array[$i]}";
            }
        }
        $base_codes = str_replace("{{__NAMESPACE__}}", "{$controller_main_path};", $base_codes);

        /**
         * Model
         * */
        $model_path = str_replace("/", "\\", $model_path);
        $base_codes = str_replace("{{__MODEL_PATH__}}", "App\\{$model_path} as {$model_name};", $base_codes);

        /**
         * View
         * */
        $view_path = "";
        for($i = 0; $i < count($dir); $i++) {
            $view_path .= "{$dir[$i]}.";
        }
        $view_path .= $tablename;
        $base_codes = str_replace("{{__VIEW_PATH__}}", $view_path, $base_codes);

        /**
         * Generate field to string
         * */
        $fields_to_get = "";
        $fields_to_insert = "";
        $ignored_fields = ["id", "created_date", "created_by", "updated_date", "updated_by", "deleted"];

        for($i = 0; $i < count($columns); $i++) {
            $fields_to_get .= "'{$columns[$i]->column_name}'";
            if($i < count($columns) - 1) $fields_to_get .= ",";

            if(!in_array($columns[$i]->column_name, $ignored_fields)) {
                $fields_to_insert .= "\t\t\t\t"."'{$columns[$i]->column_name}' => ";
                $fields_to_insert .= '$request->' . "{$columns[$i]->column_name},\n";
            }
        }
        $base_codes = str_replace("{{__FIELD_TO_GET__}}", $fields_to_get, $base_codes);
        $base_codes = str_replace("{{__DATA_TO_INSERT__}}", $fields_to_insert, $base_codes);

        fputs($controller, $base_codes);
        fclose($controller);
    }

    protected function generate_model(
        $tablename,
        $camel_case_name,
        $columns,
        $dir,
        $model_path
    ): void
    {
        $model = fopen(__DIR__ . "./../../../app/{$model_path}.php", "w");
        $base_model = fopen(__DIR__ . "./../../../public/__BASE__/__MODEL__.txt", "r+");
        $base_codes = "";
        while($line = fgets($base_model, 4096)) {
            $base_codes .= $line;
        }

        /**
         * Write model base here
         * 
         * Dynamic variables detected
         * @var __NAMESPACE__ (String) for file_route
         * @var __MODEL_NAME__ (String) for model name
         * @var __TABLENAME__ (String) with table name
         * @var __FILLABLE__ (Array to String) array of fillable data(s)
         * */

        $base_codes = str_replace("{{__MODEL_NAME__}}", $camel_case_name, $base_codes);
        $base_codes = str_replace("{{__TABLENAME__}}", $tablename, $base_codes);

        /**
         * Namespace
         * */
        $model_main_path = "App";
        $model_array = explode("/", $model_path);
        for($i = 0; $i < count($model_array); $i++) {
            if($i < (count($model_array) - 1)) {
                $model_main_path .= "\\{$model_array[$i]}";
            }
        }
        $base_codes = str_replace("{{__NAMESPACE__}}", "{$model_main_path};", $base_codes);

        /**
         * Fillable
         * */
        $fillable_strings = "[\n";
        for($i = 0; $i < count($columns); $i++) {
            $column = $columns[$i]->column_name;
            $fillable_strings .= "\t\t'$column',\n";
        }
        $fillable_strings .= "\t];";
        $base_codes = str_replace("{{__FILLABLE__}}", $fillable_strings, $base_codes);

        fputs($model, $base_codes);
        fclose($model);
    }

    protected function generate_view(
        $tablename,
        $camel_case_name,
        $columns,
        $dir,
        $view_path
    ): void
    {
        /**
         * Generate list - view
         * 
         * @var __MAIN_ROUTE__ (String) for calling routes
         * @var __TABLE_ROW__ (Array to String) list column inside body <th>
         * @var __AJAX_URL__ (String) route for calling list - serverside
         * @var __TABLE_COLUMNS__ (Array to String) for append data(s) from serverside
         * */

        $list_view = fopen(__DIR__ . "./../../../{$view_path}/{$tablename}/list.blade.php", "w");
        $list_base = fopen(__DIR__ . "./../../../public/__BASE__/__VIEW_LIST__.txt", "r+");
        $list_codes = "";
        while($line = fgets($list_base, 4096)) {
            $list_codes .= $line;
        }
        $list_codes = str_replace("{{__MAIN_ROUTE__}}", "/{$tablename}", $list_codes);
        $list_codes = str_replace("{{__AJAX_URL__}}", "/{$tablename}", $list_codes);

        $column_for_inputs = [];

        /**
         * Append Table Row and Column
         * */
        $table_row = "";
        $table_column = "[\n";
        $list_row = 0;
        $exception_columns = ["id", "created_date", "created_by", "updated_date", "updated_by", "deleted"];
        for($i = 0; $i < count($columns); $i++) {
            if(!in_array($columns[$i]->column_name, $exception_columns)) {
                if($list_row > 0) $table_row .= "\t\t\t\t\t\t\t\t";
                $list_row++;

                $table_row .= '<th class="pt-0">'.$this->upper_first_letter($columns[$i]->column_name)."</th>\n";
                $table_column .= "\t\t\t\t{\n";
                $table_column .= "\t\t\t\t\tdata: '{$columns[$i]->column_name}',\n";
                $table_column .= "\t\t\t\t\tvalue: '{$columns[$i]->column_name}'\n";
                $table_column .= "\t\t\t\t},\n";
            }

            if(!in_array($columns[$i]->column_name, $exception_columns)) {
                array_push($column_for_inputs, [
                    'name' => $columns[$i]->column_name,
                    'type' => $columns[$i]->udt_name
                ]);
            }
        }
        $table_column .= "\t\t\t]";
        $list_codes = str_replace("{{__TABLE_ROW__}}", $table_row, $list_codes);
        $list_codes = str_replace("{{__TABLE_COLUMNS__}}", $table_column, $list_codes);

        /**
         * Append and close file
         * */
        fputs($list_view, $list_codes);
        fclose($list_view);


        /**
         * Generate form - view
         * */
        $create_view = fopen(__DIR__ . "./../../../{$view_path}/{$tablename}/create.blade.php", "w");
        $detail_view = fopen(__DIR__ . "./../../../{$view_path}/{$tablename}/detail.blade.php", "w");
        $form_base = fopen(__DIR__ . "./../../../public/__BASE__/__VIEW_FORM__.txt", "r+");
        $create_codes = "";
        $detail_codes = "";
        while($line = fgets($form_base, 4096)) {
            $create_codes .= $line;
            $detail_codes .= $line;
        }

        /**
         * Function to generate inputs - Anonymous
         * */
        function generate_inputs($cols = [], $is_update = false)
        {
            $total_columns = ceil(count($cols)/2);

            /**
             * For update
             * */
            $inputs = "";
            if($is_update) {
                $inputs .= '<input type="hidden" name="id" value="{{ isset($request->id) ? $request->id : null }}" />'."\n";
            }

            $inputs .= '<div class="row">'."\n";
                $inputs .= "\t\t\t\t\t\t".'<div class="col-6">'."\n";
                    for($i = 0; $i < $total_columns; $i++) {
                        $value = "";
                        if($is_update) {
                            $value = '{{isset($request->'.$cols[$i]['name'].') ? $request->'.$cols[$i]['name'].' : ""}}';
                        }

                        $inputs .= "\t\t\t\t\t\t\t".'<div class="mb-3">'."\n";
                            $inputs .= "\t\t\t\t\t\t\t\t".'<label for="'.$cols[$i]['name'].'" class="form-label">'.$cols[$i]['name'].'</label>'."\n";
                            $inputs .= "\t\t\t\t\t\t\t\t".'<input type="text" class="form-control" id="'.$cols[$i]['name'].'" name="'.$cols[$i]['name'].'" autocomplete="off" placeholder="'.$cols[$i]['name'].'" value="'.$value.'">'."\n";
                        $inputs .= "\t\t\t\t\t\t\t".'</div>'."\n";
                    }
                $inputs .= "\t\t\t\t\t\t".'</div>'."\n";
                $inputs .= "\t\t\t\t\t\t".'<div class="col-6">'."\n";
                    for($i = $total_columns; $i < ($total_columns*2); $i++) {
                        if (isset($cols[$i])) {
                            $value = "";
                            if($is_update) {
                                $value = '{{$request->'.$cols[$i]['name'].'}}';
                            }

                            $inputs .= "\t\t\t\t\t\t\t".'<div class="mb-3">'."\n";
                                $inputs .= "\t\t\t\t\t\t\t\t".'<label for="'.$cols[$i]['name'].'" class="form-label">'.$cols[$i]['name'].'</label>'."\n";
                                $inputs .= "\t\t\t\t\t\t\t\t".'<input type="text" class="form-control" id="'.$cols[$i]['name'].'" name="'.$cols[$i]['name'].'" autocomplete="off" placeholder="'.$cols[$i]['name'].'" value="'.$value.'">'."\n";
                            $inputs .= "\t\t\t\t\t\t\t".'</div>'."\n";
                        }
                    }
                $inputs .= "\t\t\t\t\t\t".'</div>'."\n";
            $inputs .= "\t\t\t\t\t".'</div>'."\n";
            return $inputs;
        }

        /**
         * Append and close file - create
         * */
        $create_codes = str_replace("{{__MAIN_ROUTE__}}", "/{$tablename}", $create_codes);
        $create_codes = str_replace("{{__FORM_TYPE__}}", "Create", $create_codes);
        $create_codes = str_replace("{{__FORM_ACTION__}}", "create", $create_codes);
        $create_codes = str_replace("{{__PRIMARY_KEY__}}", "", $create_codes);
        $create_codes = str_replace("{{__INPUTS__}}", generate_inputs($column_for_inputs), $create_codes);

        fputs($create_view, $create_codes);
        fclose($create_view);

        /**
         * Append and close file - detail
         * */
        $detail_codes = str_replace("{{__MAIN_ROUTE__}}", "/{$tablename}", $detail_codes);
        $detail_codes = str_replace("{{__FORM_TYPE__}}", "Create", $detail_codes);
        $detail_codes = str_replace("{{__FORM_ACTION__}}", "create", $detail_codes);
        $detail_codes = str_replace("{{__PRIMARY_KEY__}}", '/{{$data->id}}', $detail_codes);
        $detail_codes = str_replace("{{__INPUTS__}}", generate_inputs($column_for_inputs, true), $detail_codes);

        fputs($detail_view, $detail_codes);
        fclose($detail_view);
    }
}
